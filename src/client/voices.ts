/** 今の状況で、ランダムな社員のひとことを1つ選ぶ。key は元のせりふ（最近出たものを避けるのに使う） */
export function pickVoice(g: Game, me: Company, recent: string[]): { e: Engineer; text: string; key: string } | null {
  const staff = me.engineers;
  if (!staff.length) return null;
  const e = staff[Math.floor(Math.random() * staff.length)];
  const proj = me.projects.find(p => hasSlot(e.assign, p.id));
  const top = (Object.entries(e.skills) as [Skill, number][]).sort((a, b) => b[1] - a[1])[0]?.[0] ?? null;
  const x: Ctx = { g, me, e, proj, top };
  const pool: { w: number; lines: string[] }[] = [];
  for (const r of RULES) {
    if (!r.when(x)) continue;
    const fresh = r.lines(x).filter(l => !recent.includes(l));
    if (fresh.length) pool.push({ w: r.w, lines: fresh });
  }
  if (!pool.length) return null;
  let t = Math.random() * pool.reduce((s, p) => s + p.w, 0);
  const chosen = pool.find(p => (t -= p.w) < 0) || pool[pool.length - 1];
  const key = chosen.lines[Math.floor(Math.random() * chosen.lines.length)];
  const rivals = g.companies.filter(c => c.id !== me.id);
  const text = key
    .replace(/\{name\}/g, lastName(e.name))
    .replace(/\{co\}/g, me.name)
    .replace(/\{proj\}/g, proj?.name || '案件')
    .replace(/\{rival\}/g, rivals.length ? rivals[Math.floor(Math.random() * rivals.length)].name : 'ライバル')
    .replace(/\{skill\}/g, top ? SKILL_NAME[top] : '仕事')
    .replace(/\{boss\}/g, '社長')
    .replace(/\{fund\}/g, g.funds?.find(f => f.id === me.invest?.[0]?.fund)?.name || '投資先');
  return { e, text, key };
}

